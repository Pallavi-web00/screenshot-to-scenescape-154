/**
 * Regenerates the dotted world map in src/lib/world-dots.ts.
 *
 * Run:  bun scripts/generate-world-dots.ts [land-110m.json] [output.ts]
 * Input defaults to Natural Earth land-110m (public domain) from the world-atlas CDN;
 * output defaults to src/lib/world-dots.ts. The map frame (longitude/latitude crop,
 * projection, dot spacing) is imported from src/lib/world-map.ts so the dots and the
 * markers can never drift apart.
 */
import { readFile, writeFile } from "node:fs/promises";

import {
  LAT_BOTTOM,
  LAT_TOP,
  LON0,
  LON1,
  MAP_SCALE,
  MAP_WIDTH,
  STEP,
  miller,
} from "../src/lib/world-map";

const SOURCE_URL = "https://cdn.jsdelivr.net/npm/world-atlas@2/land-110m.json";
const DEFAULT_OUTPUT = new URL("../src/lib/world-dots.ts", import.meta.url).pathname;

type Topology = {
  transform: { scale: [number, number]; translate: [number, number] };
  arcs: [number, number][][];
  objects: {
    land: { geometries: { type: "Polygon" | "MultiPolygon"; arcs: number[][] | number[][][] }[] };
  };
};
type Ring = Float64Array; // flat [lon0, lat0, lon1, lat1, ...]

async function loadTopology(path?: string): Promise<Topology> {
  if (path) return JSON.parse(await readFile(path, "utf8")) as Topology;
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Could not download ${SOURCE_URL}: ${res.status}`);
  return (await res.json()) as Topology;
}

/** Decodes delta-encoded TopoJSON arcs and stitches them into closed lon/lat rings. */
function landRings(topo: Topology): Ring[] {
  const [sx, sy] = topo.transform.scale;
  const [tx, ty] = topo.transform.translate;
  const arcs = topo.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * sx + tx, y * sy + ty] as const;
    });
  });

  const ring = (indexes: number[]): Ring => {
    const out: (readonly [number, number])[] = [];
    for (const i of indexes) {
      const arc = i >= 0 ? arcs[i]! : [...arcs[~i]!].reverse();
      out.push(...(out.length ? arc.slice(1) : arc));
    }
    return Float64Array.from(out.flat());
  };

  const rings: Ring[] = [];
  for (const g of topo.objects.land.geometries) {
    const polygons = (g.type === "MultiPolygon" ? g.arcs : [g.arcs]) as number[][][];
    for (const polygon of polygons) for (const r of polygon) rings.push(ring(r));
  }
  return rings;
}

/** Even-odd crossing test for one ring. */
function insideRing(ring: Ring, x: number, y: number): boolean {
  let inside = false;
  const n = ring.length / 2;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const xi = ring[i * 2]!;
    const yi = ring[i * 2 + 1]!;
    const xj = ring[j * 2]!;
    const yj = ring[j * 2 + 1]!;
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const TOP = miller(LAT_TOP);
const HEIGHT = (TOP - miller(LAT_BOTTOM)) * MAP_SCALE;
/** Map y → latitude (inverse of the Miller projection used in world-map.ts). */
const latitudeAt = (y: number) =>
  (2.5 * Math.atan(Math.exp((TOP - y / MAP_SCALE) / 1.25)) - 0.625 * Math.PI) * (180 / Math.PI);

/** Samples a hex grid over the map and run-length encodes the land dots per row. */
export function encodeWorldDots(rings: Ring[]): { encoded: string; dots: number; rows: number } {
  const rowH = (STEP * Math.sqrt(3)) / 2;
  const rows: string[] = [];
  let dots = 0;

  for (let r = 0; ; r++) {
    const y = rowH / 2 + r * rowH;
    if (y > HEIGHT) break;
    const offset = r % 2 === 0 ? 0 : STEP / 2;
    const cols = Math.floor((MAP_WIDTH - offset) / STEP) + 1;
    const lat = latitudeAt(y);

    const land: boolean[] = [];
    for (let c = 0; c < cols; c++) {
      const x = offset + STEP / 2 + c * STEP;
      if (x >= MAP_WIDTH) break;
      const lon = LON0 + (x / MAP_WIDTH) * (LON1 - LON0);
      let inside = false;
      for (const ring of rings) if (insideRing(ring, lon, lat)) inside = !inside;
      land.push(inside);
    }

    const runs: string[] = [];
    for (let c = 0; c < land.length; c++) {
      if (!land[c]) continue;
      const start = c;
      while (land[c + 1]) c++;
      runs.push(start === c ? `${start}` : `${start}-${c}`);
      dots += c - start + 1;
    }
    if (runs.length) rows.push(`${r}:${runs.join(",")}`);
  }
  return { encoded: rows.join(";"), dots, rows: rows.length };
}

async function main() {
  const [input, output = DEFAULT_OUTPUT] = process.argv.slice(2);
  const { encoded, dots, rows } = encodeWorldDots(landRings(await loadTopology(input)));
  const file = `/**
 * Dotted world map, generated by scripts/generate-world-dots.ts from Natural Earth land (public domain).
 * Format: "row:startCol-endCol,col;..." — hex grid rows on the Miller projection in world-map.ts.
 */
export const WORLD_DOT_ROWS =
  ${JSON.stringify(encoded)};
`;
  await writeFile(output, file);
  console.log(`Wrote ${dots} dots in ${rows} rows to ${output}`);
}

if (import.meta.main) await main();
